local last_time = GameGetRealWorldTimeSinceStarted()
local current_fps = 0
local times = {}
function OnWorldPostUpdate()
	while last_handled_entity < EntitiesGetMaxID() do
		process_entity( last_handled_entity )
		last_handled_entity = last_handled_entity + 1
	end
	for _,boss_centipede in ipairs(EntityGetWithTag("boss_centipede_active")) do
		if not EntityHasVarTag( boss_centipede, "gkbrkn_hero_mode" ) then
			hero_mode_process_entity( boss_centipede )
		end
	end

	--[[ More Accurate Smoothed FPS ]]
	local now = GameGetRealWorldTimeSinceStarted()
	local time_sum = 0
	table.insert( times, now - last_time )
	last_time = now
	if #times > 5 then table.remove( times, 1 ) end
	for k,v in ipairs( times ) do time_sum = time_sum + v end
	local fps = math.floor( (1 / (time_sum / #times) ) )
	current_fps = current_fps + ( fps - current_fps ) / 4
	GlobalsSetValue( "gkbrkn_fps", tostring( math.ceil( current_fps ) ) )

	local x, y = 0, 0
	local player = EntityGetWithTag( "player_unit" )[1]
	if player == nil or player == 0 then
		player = ( find_polymorphed_players() or {} )[1]
	end
	if player ~= nil and player ~= 0 then
		x, y = EntityGetTransform( player )
		if is_fixed_camera == nil then is_fixed_camera = not setting_get( MISC.FixedCamera.EnabledFlag, false ) end
		if setting_get( MISC.FixedCamera.EnabledFlag, false ) and not setting_get( MISC.FixedCamera.OldBehaviourFlag, false ) then
			if is_fixed_camera then
				local cx, cy = GameGetCameraPos()
				GameSetCameraPos( cx + ( x - cx ) / 1.2, cy + ( y - cy ) / 1.2 )
			else
				GameSetCameraFree( true )
				is_fixed_camera = true
			end
		elseif not setting_get( MISC.FixedCamera.EnabledFlag, false ) or setting_get( MISC.FixedCamera.OldBehaviourFlag, false ) then
			if is_fixed_camera then
				GameSetCameraFree( false )
				is_fixed_camera = false
			end
		end
	end

	if setting_get( FLAGS.ShowHitboxes, false ) then
		for tag in string.gmatch( setting_get( FLAGS.ShowHitboxesString, "" ), "[^,]+") do
			local targets = EntityGetWithTag( tag )
			for _,target in pairs(targets) do
				if not EntityHasTag( target, "gkbrkn_show_hitbox" ) then
					EntityAddTag( target, "gkbrkn_show_hitbox" )

					local origin = EntityLoad( "mods/gkbrkn_noita/files/gkbrkn/misc/hitboxes/origin.xml" )
					EntityAddChild( target, origin )

					local components = EntityGetComponentIncludingDisabled( target, "HitboxComponent" ) or {}
					for _,component in pairs(components) do
						local hitbox = EntityLoad( "mods/gkbrkn_noita/files/gkbrkn/misc/hitboxes/hitbox.xml" )
						local x1 = ComponentGetValue2( component, "aabb_min_x" )
						local y1 = ComponentGetValue2( component, "aabb_min_y" )
						local x2 = ComponentGetValue2( component, "aabb_max_x" )
						local y2 = ComponentGetValue2( component, "aabb_max_y" )
						local width = x2 - x1
						local height = y2 - y1
						local rx = width / 100
						local ry = height / 100
						local sprite = EntityGetFirstComponent( hitbox, "SpriteComponent" )

						ComponentSetValue2( sprite, "has_special_scale", true )
						ComponentSetValue2( sprite, "offset_x", 50 - (x1 + width * 0.5) / rx )
						ComponentSetValue2( sprite, "offset_y", 50 - (y1 + height * 0.5) / ry )
						ComponentSetValue2( sprite, "special_scale_x", rx )
						ComponentSetValue2( sprite, "special_scale_y", ry )
						EntityAddChild( target, hitbox )
					end

					local components = EntityGetComponentIncludingDisabled( target, "MaterialAreaCheckerComponent" ) or {}
					for _,component in pairs(components) do
						local hitbox = EntityLoad( "mods/gkbrkn_noita/files/gkbrkn/misc/hitboxes/hitbox.xml" )
						local x1,y1,x2,y2 = ComponentGetValue2( component, "area_aabb" )
						local width = x2-x1
						local height = y2-y1
						local rx = width / 100
						local ry = height / 100
						local sprite = EntityGetFirstComponent( hitbox, "SpriteComponent" )

						ComponentSetValue2( sprite, "has_special_scale", true )
						ComponentSetValue2( sprite, "offset_x", 50 - (x1 + width * 0.5) / rx )
						ComponentSetValue2( sprite, "offset_y", 50 - (y1 + height * 0.5) / ry )
						ComponentSetValue2( sprite, "special_scale_x", width / 100 )
						ComponentSetValue2( sprite, "special_scale_y", height / 100 )
						EntityAddChild( target, hitbox )
					end
				end
			end
		end
	else
		local targets = EntityGetWithTag( "gkbrkn_show_hitbox" )
		for _,target in pairs(targets) do
			EntityRemoveTag( target, "gkbrkn_show_hitbox" )
			for _,child in pairs( EntityGetAllChildren( target ) or {} ) do
				if EntityHasVarTag( child, "gkbrkn_hitbox" ) then
					EntityKill( child )
				end
			end
		end
	end
end

