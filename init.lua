-- Any mods registering a button should append their id to history every WorldPreUpdate and PausePreUpdate
-- If they are the first mod in the history, clear history and reset to 0
-- Otherwise, if this mod is in the history then the previously first mod stopped registering, so clear history and reset to 0
-- This method allows mod buttons when paused and not paused, recovers if mods stop registering, doesn't care for
-- mod order, doesn't require a manager mod, doesn't have button shifting, and can be called right before the GUI function
local handle_mod_button = function( key )
	local history = GlobalsGetValue("mod_button_tr_history", "" )
	if history:sub(1,#key) == key or history:find(key) then
		history = ""
		GlobalsSetValue( "mod_button_tr_current", "0" )
	end
	GlobalsSetValue( "mod_button_tr_history", history..key.."," )
end

